#!/usr/bin/env python3
"""Turn fuxi-rd-replay --dump console output into an embedded A740 draw payload.

The console transport is lossy for bursts, so this parser merges repeated
sections and every BUFHEAD/BUFHEX chunk by (dump path, iova, offset). It
then emits a C++ header with sparse buffer bytes and the captured command
stream list.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

DUMP_RE = re.compile(r"^DUMP (\S+) chip=0x([0-9a-fA-F]+) buffers=(\d+) cmds=(\d+)$")
BUF_RE = re.compile(r"^BUF iova=0x([0-9a-fA-F]+) size=(\d+) content=(\d+)$")
HEAD_RE = re.compile(r"^BUFHEAD iova=0x([0-9a-fA-F]+) size=(\d+) ([0-9a-fA-F]*)$")
HEX_RE = re.compile(r"^BUFHEX iova=0x([0-9a-fA-F]+) off=(\d+) size=(\d+) ([0-9a-fA-F]*)$")
CMD_RE = re.compile(r"^CMD iova=0x([0-9a-fA-F]+) bytes=(\d+) parent=0x([0-9a-fA-F]+) off=(\d+)$")
WORD_RE = re.compile(r"^[0-9a-fA-F]{8}(?:[ ]+[0-9a-fA-F]{8})*[ ]*$")


def is_zero(data: bytes) -> bool:
    return not any(data)


def parse(path: Path):
    blocks = []
    cur = None
    lines = path.read_text(errors="replace").splitlines()
    i = 0
    while i < len(lines):
        line = lines[i].rstrip("\r")
        m = DUMP_RE.match(line)
        if m:
            cur = {
                "path": m.group(1),
                "chip": int(m.group(2), 16),
                "buffers": {},
                "cmds": [],
                "declared_buffers": int(m.group(3)),
                "declared_cmds": int(m.group(4)),
            }
            blocks.append(cur)
            i += 1
            continue
        if cur is None:
            i += 1
            continue
        m = BUF_RE.match(line)
        if m:
            iova, size, content = int(m.group(1), 16), int(m.group(2)), int(m.group(3))
            b = cur["buffers"].setdefault(iova, {"size": size, "content": content, "data": bytearray(), "mask": bytearray()})
            if not b["data"]:
                b["data"] = bytearray(size)
                b["mask"] = bytearray(size)
            i += 1
            continue
        m = HEAD_RE.match(line)
        if m:
            iova, hexdata = int(m.group(1), 16), m.group(3)
            b = cur["buffers"].get(iova)
            if b is not None and hexdata:
                raw = bytes.fromhex(hexdata)
                b["data"][:len(raw)] = raw
                b["mask"][:len(raw)] = b"\x01" * len(raw)
            i += 1
            continue
        m = HEX_RE.match(line)
        if m:
            iova, off, size, hexdata = int(m.group(1), 16), int(m.group(2)), int(m.group(3)), m.group(4)
            b = cur["buffers"].get(iova)
            if b is not None and hexdata:
                raw = bytes.fromhex(hexdata)
                if off + len(raw) <= len(b["data"]):
                    b["data"][off:off+len(raw)] = raw
                    b["mask"][off:off+len(raw)] = b"\x01" * len(raw)
            i += 1
            continue
        m = CMD_RE.match(line)
        if m:
            cmd = {"iova": int(m.group(1), 16), "bytes": int(m.group(2)), "parent": int(m.group(3), 16), "off": int(m.group(4))}
            cur["cmds"].append(cmd)
            # Consume the PM4 words printed on the following lines and splice
            # them into the parent buffer, so a missing RD content section does
            # not lose the command stream.
            j = i + 1
            words = []
            while j < len(lines):
                wl = lines[j].rstrip("\r")
                if not WORD_RE.match(wl):
                    break
                words.extend(int(x, 16) for x in wl.split())
                j += 1
            if words:
                b = cur["buffers"].get(cmd["parent"])
                if b is not None:
                    raw = b"".join(w.to_bytes(4, "little") for w in words)
                    end = min(len(b["data"]), cmd["off"] + len(raw))
                    b["data"][cmd["off"]:end] = raw[:end-cmd["off"]]
                    b["mask"][cmd["off"]:end] = b"\x01" * (end-cmd["off"])
            i = j
            continue
        i += 1
    return blocks


def choose(blocks, name):
    if name:
        matches = [b for b in blocks if name in b["path"]]
    else:
        matches = [b for b in blocks if b["declared_cmds"] >= 1 and b["declared_buffers"] >= 1]
    if not matches:
        raise SystemExit("no matching DUMP block")
    # Prefer the most complete parse; console duplicates only make this safer.
    return max(matches, key=lambda b: (len(b["buffers"]), sum(len(v["data"]) for v in b["buffers"].values()), len(b["cmds"])))


def emit(block, out: Path):
    lines = []
    lines.append("// Generated by fuxi-rd-dump-to-header.py; do not edit.")
    lines.append("#pragma once")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append(f"static const uint32_t kA740Chip = 0x{block['chip']:x}u;")
    lines.append("struct A740BufDef { uint64_t iova; uint32_t size; const char *hex; };")
    lines.append("struct A740CmdDef { uint64_t iova; uint32_t bytes; };")
    lines.append("static const A740BufDef kA740Bufs[] = {")
    for iova in sorted(block["buffers"]):
        b = block["buffers"][iova]
        data = bytes(b["data"])
        # Trim trailing zeros but keep all captured nonzero spans.
        last = len(data)
        while last > 0 and data[last-1] == 0:
            last -= 1
        if last == 0:
            lines.append(f"    {{0x{iova:x}ull, {b['size']}u, nullptr}},")
            continue
        hexs = data[:last].hex()
        chunks = [hexs[i:i+2048] for i in range(0, len(hexs), 2048)]
        lines.append(f"    {{0x{iova:x}ull, {b['size']}u,")
        for c in chunks:
            lines.append(f'        "{c}"')
        lines.append("    },")
    lines.append("};")
    lines.append("static const A740CmdDef kA740Cmds[] = {")
    for c in block["cmds"]:
        lines.append(f"    {{0x{c['iova']:x}ull, {c['bytes']}u}},")
    lines.append("};")
    lines.append(f"static const unsigned kA740BufCount = sizeof(kA740Bufs)/sizeof(kA740Bufs[0]);")
    lines.append(f"static const unsigned kA740CmdCount = sizeof(kA740Cmds)/sizeof(kA740Cmds[0]);")
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}: bufs={len(block['buffers'])} cmds={len(block['cmds'])}")
    for iova in sorted(block["buffers"]):
        b = block["buffers"][iova]
        nz = sum(1 for x in b["data"] if x)
        print(f"  iova=0x{iova:x} size={b['size']} content={b['content']} nonzero={nz}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("log")
    ap.add_argument("-o", "--output", required=True)
    ap.add_argument("--name", default="submit00002")
    args = ap.parse_args()
    blocks = parse(Path(args.log))
    print(f"blocks={len(blocks)}")
    for i, b in enumerate(blocks):
        print(f"  [{i}] {b['path']} bufs={len(b['buffers'])} cmds={len(b['cmds'])} decl={b['declared_buffers']}/{b['declared_cmds']}")
    block = choose(blocks, args.name)
    emit(block, Path(args.output))


if __name__ == "__main__":
    main()
